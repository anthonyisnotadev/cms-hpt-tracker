'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../..');
const audit = path.join(root, 'data/hpt-audit');
const proof = JSON.parse(fs.readFileSync(path.join(audit, 'reconciliation-huntsville-current-page-recheck-2026-09-20.json'), 'utf8'));
const file = path.join(audit, 'reconciliation-manual-access-observations.json');
const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
if (!Array.isArray(doc.records)) throw new Error('manual observation file must contain records');
const existing = doc.records.find(row => row.ccn === proof.ccn);
const record = existing || { ccn: proof.ccn };
record.observed_at = proof.observed_at;
record.proof_file = 'reconciliation-huntsville-current-page-recheck-2026-09-20.json';
record.official_site = 'https://www.huntsvillehospital.org/';
record.official_pricing_page = proof.official_pricing_page;
record.official_page_observation = proof.official_page_observation;
record.pointer_url = proof.pointer_url;
record.pointer_result = proof.pointer_result;
record.candidate_mrf_url = proof.candidate_mrf_url;
record.candidate_mrf_result = proof.candidate_mrf_result;
record.disposition = proof.disposition;
record.next_action = proof.next_action;
if (!existing) doc.records.push(record);
doc.records.sort((a, b) => String(a.ccn).localeCompare(String(b.ccn)));
fs.writeFileSync(file, `${JSON.stringify(doc, null, 2)}\n`);
console.log(JSON.stringify({ applied: proof.ccn, created: !existing, disposition: record.disposition }, null, 2));
