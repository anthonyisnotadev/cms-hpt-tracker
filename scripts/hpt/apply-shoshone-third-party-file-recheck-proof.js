'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..'),audit=path.join(root,'data/hpt-audit');
const proofName='reconciliation-shoshone-third-party-file-recheck-proof-2026-09-25.json';
const p=JSON.parse(fs.readFileSync(path.join(audit,proofName),'utf8'));
const fp=path.join(audit,'reconciliation-manual-access-observations.json');
const doc=JSON.parse(fs.readFileSync(fp,'utf8'));
const i=doc.records.findIndex(x=>x.ccn===p.ccn); if(i<0) throw new Error('missing CCN '+p.ccn);
const prior=doc.records[i];
doc.records[i]={...prior, latest_third_party_file_recheck_2026_09_25:{proof_file:proofName,observed_at:p.observed_at,source_page_url:p.source_page_url,candidate_file_url:p.candidate_file_url,candidate_file_status:p.candidate_file_status,candidate_file_observation:p.candidate_file_observation,disposition:p.disposition}, next_action:p.next_action};
doc.records.sort((a,b)=>a.ccn.localeCompare(b.ccn));
fs.writeFileSync(fp,JSON.stringify(doc,null,2)+'\n');
