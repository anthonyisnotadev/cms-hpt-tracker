'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = path.resolve(__dirname, '../..');
const audit = path.join(root, 'data/hpt-audit');
const proof = JSON.parse(fs.readFileSync(path.join(audit, 'reconciliation-cobre-valley-current-file-recheck-2026-09-20.json'), 'utf8'));
const samplePath = path.join(root, proof.retained_sample);
fs.mkdirSync(path.dirname(samplePath), { recursive: true });
const rawPointer = fs.readFileSync(path.join(root, 'cms_data/hpt/pointer-corpus/raw/cvrmc.org-3537bf38c8c9.txt'));
if (crypto.createHash('sha256').update(rawPointer).digest('hex') !== proof.pointer_historical_sha256) throw new Error('Historical pointer hash changed');
const https = require('https');
const request = https.request(new URL(proof.pointer_declared_mrf_url), { headers: { Range: 'bytes=0-262143' } }, response => {
  const chunks = [];
  response.on('data', chunk => chunks.push(chunk));
  response.on('end', () => {
    const bytes = Buffer.concat(chunks);
    const sha = crypto.createHash('sha256').update(bytes).digest('hex');
    if (response.statusCode !== proof.mrf_http_status || bytes.length !== proof.mrf_sample_bytes || sha !== proof.mrf_sample_sha256) throw new Error('Fresh Cobre Valley sample changed');
    fs.writeFileSync(samplePath, bytes);
    const file = path.join(audit, 'reconciliation-manual-access-observations.json');
    const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
    const existing = doc.records.find(row => row.ccn === proof.ccn);
    const record = existing || { ccn: proof.ccn };
    record.observed_at = proof.observed_at;
    record.proof_file = 'reconciliation-cobre-valley-current-file-recheck-2026-09-20.json';
    record.official_site = proof.official_site;
    record.identity_page_url = proof.identity_page_url;
    record.pointer_url = proof.pointer_url;
    record.pointer_historical_sha256 = proof.pointer_historical_sha256;
    record.pointer_current_result = proof.pointer_current_result;
    record.pointer_declared_mrf_url = proof.pointer_declared_mrf_url;
    record.mrf_http_status = proof.mrf_http_status;
    record.mrf_sample_bytes = proof.mrf_sample_bytes;
    record.mrf_sample_sha256 = proof.mrf_sample_sha256;
    record.retained_sample = proof.retained_sample;
    record.declared_hospital_name = proof.declared_hospital_name;
    record.declared_location_name = proof.declared_location_name;
    record.declared_address = proof.declared_address;
    record.declared_license_state = proof.declared_license_state;
    record.declared_last_updated = proof.declared_last_updated;
    record.cms_template_version = proof.cms_template_version;
    record.disposition = proof.disposition;
    record.next_action = proof.next_action;
    if (!existing) doc.records.push(record);
    doc.records.sort((a, b) => String(a.ccn).localeCompare(String(b.ccn)));
    fs.writeFileSync(file, `${JSON.stringify(doc, null, 2)}\n`);
    console.log(JSON.stringify({ applied: proof.ccn, created: !existing, sample: proof.mrf_sample_sha256 }, null, 2));
  });
});
request.on('error', error => { throw error; });
request.end();
